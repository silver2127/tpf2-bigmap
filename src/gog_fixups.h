struct GogFixupSet { uintptr_t steamRva; const GogFixup* fixups; size_t count; };
#define GOG_FIXUP_SET(rva, t) { rva, t, sizeof t / sizeof t[0] }
static const GogFixupSet kGogFixupSets[] = {
    GOG_FIXUP_SET(0x3ac6d4, kGogFixRefineBody),
    GOG_FIXUP_SET(0x3b3485, kGogFixAlignBody),
    GOG_FIXUP_SET(0x3b0190, kGogFixAlignPredCtor),
    GOG_FIXUP_SET(0x3af850, kGogFixAlignResize),
};
#undef GOG_FIXUP_SET

// On GOG, rewrite the relative fields of the region that starts at Steam RVA
// `steamRva` so `bytes` holds what the GOG executable must contain there.
// A region without a fixup set is left as is (it has no differing field).
// Returns false when the region cannot be placed on GOG at all.
static bool GogFixRegion(uintptr_t steamRva, uint8_t* bytes, uint32_t size)
{
    if (!g_gog) return true;
    const uintptr_t gog = GogRva(steamRva);
    if (!gog) return false;
    for (const auto& set : kGogFixupSets) {
        if (set.steamRva != steamRva) continue;
        for (size_t i = 0; i < set.count; ++i) {
            const GogFixup& f = set.fixups[i];
            if (uint32_t(f.disp) + 4 > size || f.end > size) return false;
            const int32_t d = int32_t(int64_t(f.gogTarget) - int64_t(gog + f.end));
            memcpy(bytes + f.disp, &d, 4);
        }
    }
    return true;
}
