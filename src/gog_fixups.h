// gog_fixups.h -- RIP-relative and rel32 fields of the code regions that
// Steam-RVA modules verify byte for byte, as they read on the GOG 2024-12-12
// executable. The code is the same on both builds but the regions it refers
// to (.rdata, the CRT, the assert handler) are shifted by different amounts,
// so those fields alone differ. On GOG a module rewrites exactly these fields
// in its expected bytes before verifying; every other byte is still compared.
// Each entry: displacement offset and instruction end, both from the region
// start, and the GOG RVA the field must point at. Generated by
//   python tools/gog_align_code.py --emit <name> <GOG exe> <steam> <gog> @<hex>
// which also checks that every other byte of the region is identical.
#pragma once

struct GogFixup { uint16_t disp, end; uint32_t gogTarget; };

