"""Map the Steam 35924 sites of the plugin's modules onto the GOG 2024-12-12 exe.

Reads src/*.h for every (Steam RVA, expected bytes) pair a module verifies,
finds those bytes in the GOG TransportFever2.exe and picks the match nearest
the shift of the neighbouring sites. Writes nothing unless --emit is given, in
which case it prints the C++ table for src/gog_rva.h.

Read-only on the exe. Usage:
    python tools/gog_map_sites.py <GOG TransportFever2.exe> [--emit] [--modules a,b]
"""
import argparse
import re
import struct
import sys
from pathlib import Path

import pefile

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'src'

# Steam -> GOG pairs already measured and shipped in bigmap.cpp, used to
# predict the shift of a region before searching.
KNOWN = [
    (0x9d800, 0x9da10), (0xbbd90, 0xbbfa0), (0x2304f8, 0x230718),
    (0x66ce7e, 0x66d09e), (0x674aa0, 0x674cc0), (0x90d410, 0x90d500),
    (0x2326290, 0x2328dc0),
]

BYTE_LIST = re.compile(r'0x[0-9A-Fa-f]{1,2}\b')


def parse_bytes(body):
    return bytes(int(x, 16) for x in BYTE_LIST.findall(body))


def arrays(text):
    """name -> bytes for every `NAME[..] = { 0x.., ... }` byte array."""
    out = {}
    for m in re.finditer(r'(\w+)\s*\[\s*\w*\s*\]\s*=\s*\{([^{}]*)\}', text):
        b = parse_bytes(m.group(2))
        if b:
            out[m.group(1)] = b
    return out


def consts(text):
    out = {}
    for m in re.finditer(r'\b(k\w+|RVA_\w+|kRva\w*|\w+Rva)\s*=\s*(0x[0-9A-Fa-f]+)', text):
        out[m.group(1)] = int(m.group(2), 16)
    return out


def sites_of(path):
    """(rva, bytes, origin) pairs a module verifies."""
    text = path.read_text(encoding='utf-8', errors='replace')
    arr, cst = arrays(text), consts(text)
    found = []
    # H->verifyBytes(RVA, ARRAY, ...)
    for m in re.finditer(r'verifyBytes\(\s*([\w]+)\s*,\s*([\w]+)\s*,', text):
        r, a = m.group(1), m.group(2)
        rva = int(r, 16) if r.startswith('0x') else cst.get(r)
        if rva is not None and a in arr:
            found.append((rva, arr[a], f'{path.name}:{a}'))
    # table rows: {0xRVA, "name"?, {bytes}, ...} and {0xRVA, {bytes}, ...}
    for m in re.finditer(r'\{\s*(0x[0-9A-Fa-f]{4,8})\s*,\s*(?:"[^"]*"\s*,\s*)?\{([^{}]*)\}', text):
        b = parse_bytes(m.group(2))
        if len(b) >= 4:
            found.append((int(m.group(1), 16), b, f'{path.name}:row'))
    # unique by rva
    seen, out = set(), []
    for s in found:
        if s[0] not in seen:
            seen.add(s[0]); out.append(s)
    return out


class Exe:
    def __init__(self, path):
        self.pe = pefile.PE(path, fast_load=True)
        self.secs = [(s.VirtualAddress, s.get_data()) for s in self.pe.sections]

    def find_all(self, pat):
        out = []
        for va, data in self.secs:
            i = data.find(pat)
            while i >= 0:
                out.append(va + i); i = data.find(pat, i + 1)
        return out


def predict(rva, anchors):
    a = min(anchors, key=lambda p: abs(p[0] - rva))
    return rva + (a[1] - a[0])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('exe')
    ap.add_argument('--modules', default='')
    ap.add_argument('--emit', action='store_true')
    args = ap.parse_args()
    exe = Exe(args.exe)
    files = sorted(SRC.glob('*.h'))
    if args.modules:
        want = set(args.modules.split(','))
        files = [f for f in files if f.stem in want]
    anchors = list(KNOWN)
    rows, report = [], []
    for f in files:
        for rva, pat, origin in sites_of(f):
            hits = exe.find_all(pat)
            if not hits:
                report.append((origin, rva, None, 'NOT FOUND', len(pat))); continue
            pred = predict(rva, anchors)
            best = min(hits, key=lambda h: abs(h - pred))
            delta_ok = abs(best - pred) <= 0x400
            unique = len(hits) == 1
            if delta_ok:
                status = 'unique' if unique else f'{len(hits)} hits, nearest'
            else:
                status = 'unique, OFF-SHIFT' if unique else f'{len(hits)} hits, AMBIGUOUS'
            # Only a match that agrees with its region's shift is trusted, and
            # only those become anchors: one stray unique match must not move
            # the prediction for its neighbours.
            if delta_ok:
                anchors.append((rva, best)); rows.append((rva, best, origin))
            report.append((origin, rva, best, status, len(pat)))
    for origin, rva, g, status, n in sorted(report, key=lambda r: r[1]):
        gs = f'{g:#x} ({g - rva:+#x})' if g is not None else '-'
        print(f'{rva:#09x} -> {gs:<22} {status:<22} {n:>3}B  {origin}')
    print(f'{len(rows)} mapped of {len(report)} verified sites')
    if args.emit:
        print('\n// --- generated by tools/gog_map_sites.py ---')
        for rva, g, origin in sorted(set(rows)):
            print(f'    {{ {rva:#09x}, {g:#09x} }},   // {origin}')


if __name__ == '__main__':
    main()
